// DecodeStandard decodes a byte slice using Standard encoding
func DecodeStandard(data []byte) string {
	runes := make([]rune, len(data))
	for i, b := range data {
		runes[i] = StandardEncoding[b]
	}
	return string(runes)
}

// DecodePDFDoc decodes a byte slice using PDFDoc encoding
func DecodePDFDoc(data []byte) string {
	runes := make([]rune, len(data))
	for i, b := range data {
		runes[i] = PDFDocEncoding[b]
	}
	return string(runes)
}
