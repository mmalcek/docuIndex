// DecodeWinAnsi decodes a byte slice using WinAnsi encoding
func DecodeWinAnsi(data []byte) string {
	runes := make([]rune, len(data))
	for i, b := range data {
		runes[i] = WinAnsiEncoding[b]
	}
	return string(runes)
}
